  <p>اسراء جلسه‌های قرآن را ساده می‌کند: جلسه‌ها را ببینید، عضو شوید، در جلسه حاضر شوید، نوبت قرائت بگیرید و بعد از قرائت ارزیابی معلم و امتیاز خود را ببینید.</p>

  <h2>چطور کار می‌کند</h2>
  <ul>
    <li><strong>قرآن‌آموز:</strong> با شمارهٔ موبایل وارد می‌شود، درخواست عضویت می‌دهد، در جلسهٔ شروع‌شده حضور ثبت می‌کند (۵ امتیاز) و وارد صف نوبت می‌شود.</li>
    <li><strong>معلم و پشتیبان:</strong> صف را زنده مدیریت و قرائت را بر اساس صوت، لحن و تجوید ارزیابی می‌کنند.</li>
    <li><strong>مدیر جلسه:</strong> جلسه را می‌سازد، زمان‌بندی می‌کند، عضویت‌ها و نقش‌ها را مدیریت می‌کند.</li>
  </ul>

  <h2>نصب روی گوشی</h2>
