<DocPage title="حریم خصوصی" subtitle="چه اطلاعاتی از شما نگه می‌داریم، برای چه و تا کی." updated="۱۴۰۵/۰۷/۱۲">
  <p>اسراء فقط اطلاعاتی را نگه می‌دارد که برای ورود، برگزاری جلسه‌ها و محاسبهٔ امتیاز لازم است. تبلیغات و ابزار ردیابی شخص‌ثالث در اسراء وجود ندارد.</p>

  <h2>اطلاعاتی که جمع‌آوری می‌کنیم</h2>
  <ul>
    <li><strong>شمارهٔ موبایل:</strong> برای ورود با کد پیامکی (OTP) و شناسایی حساب.</li>
    <li><strong>نام و نام خانوادگی:</strong> که خودتان وارد می‌کنید؛ برای نمایش در جلسه‌ها، صف نوبت و ارزیابی‌ها.</li>
    <li><strong>فعالیت در جلسه‌ها:</strong> عضویت، نقش، حضور، نوبت قرائت، ارزیابی‌ها (صوت، لحن، تجوید، یادداشت معلم) و امتیاز/نشان‌ها.</li>
    <li><strong>اطلاعات نشست:</strong> نام مرورگر/دستگاه، نشانی IP و زمان آخرین فعالیت برای نمایش «دستگاه‌ها و نشست‌های من» و امنیت حساب.</li>
    <li><strong>رمز عبور (اختیاری):</strong> فقط به‌صورت هش‌شده با الگوریتم argon2id نگه‌داری می‌شود؛ رمز اصلی هرگز ذخیره نمی‌شود.</li>
  </ul>

  <h2>پیامک</h2>
  <p>کد تأیید از طریق سرویس‌دهندهٔ پیامک (فراز اس‌ام‌اس) برای شمارهٔ شما ارسال می‌شود. فقط شمارهٔ شما و کد تأیید به آن سرویس داده می‌شود. خود کد تأیید در پایگاه‌داده ما به‌صورت رمزنگاری‌شده (HMAC) ذخیره می‌شود و بعد از ۱۲۰ ثانیه منقضی است.</p>

  <h2>کوکی و ذخیرهٔ محلی</h2>
  <ul>
    <li><strong>کوکی نشست (<span dir="ltr">isra_rt</span>):</strong> ضروری و HttpOnly است و فقط برای ادامهٔ ورود شما استفاده می‌شود؛ ۱۴ روز اعتبار دارد.</li>
    <li><strong>ذخیرهٔ مرورگر:</strong> شناسهٔ تصادفی دستگاه و یک نشانهٔ «ورود کرده‌ام» تا نشست شما شناسایی شود. هیچ‌کدام اطلاعات شخصی نیستند.</li>
  </ul>

  <h2>چه کسانی اطلاعات را می‌بینند</h2>
  <ul>
    <li>معلم، پشتیبان و مدیر هر جلسه، نام و فعالیت شما در همان جلسه را می‌بینند. سایر اعضا فقط نفر جاری و جایگاه خودتان در صف را می‌بینند.</li>
    <li>ارزیابی‌های شما را فقط خودتان و کادر همان جلسه می‌بینید.</li>
    <li>شمارهٔ موبایل شما برای سایر کاربران نمایش داده نمی‌شود.</li>
    <li>اطلاعات شما فروخته یا برای تبلیغات استفاده نمی‌شود.</li>
  </ul>

  <h2>مدت نگه‌داری</h2>
  <ul>
    <li>نشست‌های بسته‌شده پس از ۳۰ روز و کدهای تأیید پس از ۱ روز از پایگاه‌داده پاک می‌شوند.</li>
    <li>سابقهٔ جلسه‌ها، امتیاز و نشان‌ها تا زمانی که حساب فعال است نگه‌داری می‌شود (امتیاز و نشان‌ها با افت امتیاز باطل نمی‌شوند).</li>
  </ul>

  <h2>امنیت</h2>
  <p>ارتباط با سرور رمزنگاری‌شده است. نشست‌ها کوتاه‌مدت و قابل مشاهده/لغو در بخش «حساب ← دستگاه‌ها و نشست‌ها» هستند. اقدام‌های حساس مدیریتی با تأیید مجدد هویت و ثبت در گزارش انجام می‌شود.</p>
