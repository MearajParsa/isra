  <p>با ورود به اسراء این شرایط را می‌پذیرید. اسراء یک پلتفرم برای برگزاری جلسه‌های قرآن است: عضویت، حضور، نوبت قرائت، ارزیابی و امتیاز.</p>

  <h2>حساب کاربری</h2>
  <ul>
    <li>حساب با شمارهٔ موبایل شما ساخته می‌شود؛ مسئولیت دسترسی به آن شماره و نگه‌داری رمز (در صورت تعیین) با شماست.</li>
    <li>در صورت گم شدن دستگاه می‌توانید از «حساب ← دستگاه‌ها و نشست‌ها» نشست‌ها را لغو کنید.</li>
  </ul>

  <h2>جلسه‌ها و نقش‌ها</h2>
  <ul>
    <li>مدیر جلسه، عضویت‌ها را تأیید یا رد می‌کند؛ پشتیبان و معلم صف نوبت را مدیریت می‌کنند.</li>
    <li>ارزیابی فقط توسط معلم و پشتیبان جلسه ثبت می‌شود و هدف آن آموزش و بازخورد است؛ در ارزیابی‌ها ادب و انصاف را رعایت کنید.</li>
    <li>وضعیت جلسه فقط رو‌به‌جلو تغییر می‌کند: پیش‌نویس، منتشرشده، در حال برگزاری، پایان‌یافته.</li>
  </ul>

  <h2>امتیاز و نشان</h2>
  <p>ثبت حضور در هر جلسه فقط یک‌بار ۵ امتیاز دارد. امتیاز ارزیابی طبق وزن‌های تعیین‌شده توسط مدیریت سیستم محاسبه می‌شود. نشان‌ها پس از کسب باطل نمی‌شوند. تلاش برای دستکاری امتیاز یا سوءاستفاده از سامانه ممنوع است.</p>

  <h2>رفتار قابل قبول</h2>
  <ul>
    <li>از ثبت اطلاعات نادرست، مزاحمت برای سایر کاربران یا تلاش برای دور زدن محدودیت‌های امنیتی خودداری کنید.</li>
    <li>مدیریت می‌تواند برای حفظ امنیت و نظم، دسترسی کاربران متخلف را محدود کند.</li>
  </ul>

  <h2>دسترسی و تغییرات</h2>
  <p>تلاش می‌کنیم سامانه همواره در دسترس باشد، اما ممکن است برای نگه‌داری موقتاً متوقف شود. این شرایط ممکن است به‌روزرسانی شود؛ نسخهٔ جدید در همین صفحه منتشر می‌شود. نحوهٔ نگه‌داری اطلاعات در صفحهٔ <a href="/privacy">حریم خصوصی</a> آمده است.</p>
